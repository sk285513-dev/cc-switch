import json

def generate_600_cases():
    cases = []
    
    # 法律領域
    domains = ["民法", "刑法", "行政法", "民事訴訟法", "刑事訴訟法", "公司法", "保險法", "票據法", "土地法", "家事事件法"]
    
    # 行為主體
    subjects = ["甲", "乙", "丙", "公司負責人", "公務員", "未成年人", "法定代理人", "繼承人", "背書人", "承租人"]
    
    # 爭議情境
    scenarios = [
        "發生車禍，無照駕駛且逆向行駛",
        "訂立買賣契約後，發現物有重大瑕疵",
        "未經同意擅自將共有土地設定抵押權",
        "因信賴行政機關之函釋而為投資，後函釋遭廢止",
        "在捷運上遭遇隨機攻擊，為奪刀而將歹徒重傷",
        "公司董事長未經股東會決議，擅自為他人作保",
        "開立支票後，主張原因關係不存在而拒絕付款",
        "未告知既往症即投保人壽保險，保險公司欲解除契約",
        "提起訴訟後，發現已逾越消滅時效 15 年",
        "對於違法之行政處分未於 30 日內提起訴願",
        "將名下房產借名登記於親友名下，親友卻擅自出售",
        "配偶外遇並有家暴行為，訴請離婚並爭取親權"
    ]
    
    # 法律爭點/問題
    questions = [
        "請問依實務見解，應如何分配過失比例？",
        "得否主張解除契約或請求減少價金？",
        "該抵押權設定之效力為何？",
        "有無信賴保護原則之適用？",
        "是否構成正當防衛？有無防衛過當之適用？",
        "該保證契約對公司是否生效？",
        "執票人得否主張票據抗辯之切斷？",
        "保險公司解除契約是否合法？",
        "法院應如何下判決？",
        "該行政處分是否發生形式存續力？",
        "出賣行為之效力為何？",
        "法院於酌定親權時，應考量哪些子女最佳利益原則？"
    ]
    
    case_id = 1
    for d in domains:
        for sub in subjects:
            for scen, q in zip(scenarios, questions):
                if case_id > 600:
                    break
                # 組合出多樣化的案情
                case_text = f"【{d}領域】{sub}{scen}，{q}"
                cases.append(case_text)
                case_id += 1
                
    # 補足剩餘的狀態 (若有不足)
    while case_id <= 600:
        cases.append(f"極端壓力測試案情 {case_id}：這是一段用於測試系統承載邊界的自動生成文本，請忽略語義並分析潛在法律風險。")
        case_id += 1
        
    with open(r"C:\LocalAI_Workstation\600_test_cases.json", "w", encoding="utf-8") as f:
        json.dump(cases[:600], f, ensure_ascii=False, indent=2)
        
    print(f"成功生成 {len(cases[:600])} 筆獨立法律測試案情！")

if __name__ == "__main__":
    generate_600_cases()
