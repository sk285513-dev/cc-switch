# 單一真相來源 (SSOT): 國家考試科目權重邏輯
# 分數越低優先權越高

NATIONAL_EXAM_WEIGHTS = {
    "憲法": 10,
    "身分法": 20,
    "民法": 20,
    "刑法": 25,
    "行政法": 30,
    "民事訴訟法": 40,
    "民訴": 40,
    "刑事訴訟法": 40,
    "刑訴": 40,
    "家事事件法": 40,
    "家事": 40,
    "土地法規": 50,
    "土地法": 50,
    "公司法": 60,
    "票據法": 60,
    "證券交易法": 60,
    "證交法": 60,
    "稅法": 60,
}

def get_exam_score(subject_name: str) -> int:
    """
    依據科目名稱回傳國考權重分數。
    分數越小代表優先級越高 (10 分為最高優先級)。
    如果非國考科目，則回傳 999 視為最低優先級。
    """
    for subject, score in NATIONAL_EXAM_WEIGHTS.items():
        if subject in subject_name:
            return score
    return 999
