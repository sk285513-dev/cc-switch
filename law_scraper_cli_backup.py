def run_independent_scraper():
    update_status("running", 5, "正在初始化 API 爬蟲環境與多目標備援清單...")
    time.sleep(1)
    
    question_cards = []
    
    # 步驟 1: 嘗試對接 LawPlayer API
    update_status("running", 15, "嘗試連線標的: LawPlayer (法律人)...")
    time.sleep(1)
    
    lp_questions = fetch_from_lawplayer_api()
    if lp_questions:
        question_cards = lp_questions
        update_status("running", 30, f"LawPlayer 題庫 API 對接成功！取得 {len(lp_questions)} 題精選考古題。")
        time.sleep(1)

    if not question_cards:
        update_status("completed", 100, "同步結束：目前所有題庫網站均無新結構考題。")
        return
        
    total_questions = len(question_cards)
    update_status("running", 40, f"共發現 {total_questions} 題新考題。開始清洗與寫入 Obsidian 知識庫...")
    time.sleep(1)
    
    history = load_scraped_history()
    parsed_count = 0
    skipped_by_mem = 0
    
    for idx, q in enumerate(question_cards):
        try:
            q_id = q["id"]
            if q_id in history["scraped_questions"]:
                skipped_by_mem += 1
                continue
                
            # 寫入 Obsidian
            save_to_obsidian(q_id, q["year"], q["subject"], q["title"], q["options"], q["answer"], q["explanation"])
            
            # 寫入智慧記憶
            history["scraped_questions"][q_id] = {
                "scraped_at": datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
                "year": q["year"],
                "subject": q["subject"]
            }
            parsed_count += 1
            
            current_progress = 40 + int((parsed_count / total_questions) * 55)
            update_status("running", current_progress, f"正在解析並同步：[{q['year']} {q['subject']}] 第 {parsed_count}/{total_questions} 題...")
            time.sleep(1)
        except Exception as item_error:
            print(f"解析考題區塊發生錯誤: {item_error}")
            continue
            
    skipped_msg = f" (已跳過重複: {skipped_by_mem} 題，跳過非法律: 0 題)"
    
    # 紀錄執行日誌
    history["execution_history"].append({
        "timestamp": datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "status": "completed",
        "total_parsed": parsed_count,
        "skipped_duplicate": skipped_by_mem,
        "skipped_non_legal": 0,
        "message": f"同步成功！本次共新同步 {parsed_count} 題 LawPlayer 司法官/律師 考古題。{skipped_msg}"
    })
    history["execution_history"] = history["execution_history"][-50:]
    save_scraped_history(history)
    
    update_status("completed", 100, f"同步成功！本次共新同步 {parsed_count} 題 LawPlayer 考古題。{skipped_msg}")

if __name__ == "__main__":
    try:
        run_independent_scraper()
    except Exception as e:
        history = load_scraped_history()
        history["execution_history"].append({
            "timestamp": datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "status": "failed",
            "error": str(e),
            "message": f"排程執行發生致命崩潰: {str(e)}"
        })
        history["execution_history"] = history["execution_history"][-50:]
        save_scraped_history(history)
        update_status("failed", 100, f"排程執行發生致命崩潰: {str(e)}")
