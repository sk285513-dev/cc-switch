def update_status(status, progress, message):
    try:
        data = {
            "status": status,
            "progress": progress,
            "message": message,
            "updated_at": datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        }
        with open(PROGRESS_FILE, "w", encoding="utf-8-sig") as f:
            json.dump(data, f, ensure_ascii=False)
        print(f"[{status.upper()}] {progress}% - {message}")
    except Exception as e:
        print(f"Failed to update status: {e}")

def is_legal_text(text):
    keywords = ["法", "條", "釋字", "判決", "訴訟", "違憲", "法院", "裁判", "當事人", "損害賠償", "檢察官", "被告", "原告"]
    return sum(1 for kw in keywords if kw in text) >= 2

def save_to_obsidian(q_id, year, subject, title, options, answer, explanation):
    try:
        os.makedirs(OBSIDIAN_DIR, exist_ok=True)
        safe_subject = re.sub(r'[\\/*?:"<>|]', '_', subject)
        filename = f"{year}_{safe_subject}_{q_id}.md"
        filepath = os.path.join(OBSIDIAN_DIR, filename)
        
        content = f"# {year} {subject} 考古題\n\n"
        content += f"**【題幹】**\n{title}\n\n"
        content += "**【選項】**\n"
        for i, opt in enumerate(options):
            content += f"- ({chr(65+i)}) {opt}\n"
        content += f"\n**【正確答案】**：{answer}\n\n"
        content += f"**【實務詳解與法條關聯】**\n{explanation}\n\n"
        content += "---\n*Generated by LexMind LawPlayer Scraper API*"
        
        with open(filepath, "w", encoding="utf-8-sig") as f:
            f.write(content)
        return True
    except Exception as e:
        print(f"Failed to write to Obsidian: {e}")
        return False

def load_scraped_history():
    if os.path.exists(HISTORY_FILE):
        try:
            with open(HISTORY_FILE, "r", encoding="utf-8-sig") as f:
                data = json.load(f)
                if isinstance(data, dict):
                    if "scraped_questions" not in data:
                        return {"execution_history": [], "scraped_questions": data}
                    return data
        except Exception:
            pass
    return {"execution_history": [], "scraped_questions": {}}

def save_scraped_history(history):
    try:
        os.makedirs(os.path.dirname(HISTORY_FILE), exist_ok=True)
        with open(HISTORY_FILE, "w", encoding="utf-8-sig") as f:
            json.dump(history, f, ensure_ascii=False, indent=4)
    except Exception as e:
        print(f"Failed to save scraped history: {e}")

